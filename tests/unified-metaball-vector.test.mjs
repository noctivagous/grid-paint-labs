import { test } from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
const nct = fileURLToPath(new URL('../NCTGraphite/packages/nctgraphite/src/index.ts', import.meta.url));
const result = await build({ stdin: { contents: `export { createMetaballLayer, createInitialDocument, defaultCanvas, metaballVectorLayer, setLayerSetting, layerParameters, layerCommands, paintLayerAt, clearLayerPaint } from './unified/layers.ts'; export { vectorShapePath } from './unified/vectorShapes.ts'; export { openGridPaintFile } from './unified/records.ts';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'neutral', alias: { '@nct/nctgraphite': nct }, logLevel: 'silent' });
const api = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString('base64')}`);
const canvas = api.defaultCanvas(), point = { x: canvas.width / 2, y: canvas.height / 2 };
test('metaball vector engine paints and contours without losing the blobs', () => {
  let layer = api.createMetaballLayer({ settings: { engine: 'contour' } });
  layer = api.paintLayerAt(layer, canvas, point, 'paint');
  const blobs = layer.data.blobs;
  layer = api.setLayerSetting(layer, 'engine', 'vector', canvas);
  assert.equal(layer.data.blobs, blobs);
  assert.equal(api.metaballVectorLayer(layer, canvas).settings.shapeMode, 'magnitude');
  assert.ok(api.layerCommands(layer).some(c => c.id === 'op:swirl'));
  assert.ok(api.layerParameters(layer).some(p => p.id === 'vector:shapeMode'));
  layer = api.paintLayerAt(layer, canvas, point, 'op:swirl');
  assert.ok(layer.data.vectorField.data.vectors.some(v => Math.hypot(v.vx, v.vy) > 0));
  assert.match(api.vectorShapePath(api.metaballVectorLayer(layer, canvas), canvas.width, canvas.height), /M .* Z/);
  const vectors = layer.data.vectorField.data.vectors;
  layer = api.setLayerSetting(layer, 'engine', 'arc', canvas);
  layer = api.paintLayerAt(layer, canvas, { x: point.x + 100, y: point.y }, 'paint');
  assert.equal(layer.data.vectorField.data.vectors, vectors);
  layer = api.setLayerSetting(layer, 'engine', 'vector', canvas);
  layer = api.clearLayerPaint(layer);
  assert.equal(layer.data.blobs.length, 2);
  assert.ok(layer.data.vectorField.data.vectors.every(v => v.vx === 0 && v.vy === 0));
});
test('vector settings, grid and data persist across document save and undo', () => {
  let doc = api.createInitialDocument();
  const id = doc.layers.find(l => l.mode === 'metaball').id;
  doc = doc.updatingLayer(id, l => api.setLayerSetting(l, 'engine', 'vector', canvas));
  doc = doc.updatingLayer(id, l => api.setLayerSetting(l, 'vector:gridKind', 'hex', canvas));
  doc = doc.updatingLayer(id, l => api.setLayerSetting(l, 'vector:shapeMode', 'strokes', canvas));
  doc = doc.updatingLayer(id, l => api.paintLayerAt(l, canvas, point, 'op:swirl'));
  const original = doc.layers.find(l => l.id === id);
  const saved = api.openGridPaintFile(doc.toJSON()).layers.find(l => l.id === id);
  assert.equal(saved.settings.engine, 'vector');
  assert.equal(saved.data.vectorField.settings.gridKind, 'hex');
  assert.equal(saved.data.vectorField.settings.shapeMode, 'strokes');
  assert.deepEqual(saved.data.vectorField.data.vectors, original.data.vectorField.data.vectors);
  assert.ok(doc.undo().layers.find(l => l.id === id).data.vectorField.data.vectors.every(v => v.vx === 0 && v.vy === 0));
});

test('new metaball layers default to vector while explicit engines remain unchanged', () => {
  const layer = api.createMetaballLayer();
  assert.equal(layer.settings.engine, 'vector');
  assert.ok(api.layerParameters(layer).find(p => p.id === 'engine').defaultValue === 'vector');
  const painted = api.paintLayerAt(layer, canvas, point, 'paint');
  assert.ok(painted.data.vectorField.data.vectors.some(v => Math.hypot(v.vx, v.vy) > 0));
  for (const engine of ['arc', 'contour']) assert.equal(api.createMetaballLayer({ settings: { engine } }).settings.engine, engine);
});
