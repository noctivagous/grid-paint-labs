import { test } from 'node:test';
import assert from 'node:assert/strict';
import paper from 'paper';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
const nct = fileURLToPath(new URL('../NCTGraphite/packages/nctgraphite/src/index.ts', import.meta.url));
const result = await build({ stdin: { contents: `export { drawCellBrushPreview } from './unified/draw.ts'; export { createCellPaintLayer, defaultCanvas, paintLayerAt, setLayerSetting, cellBrushHits } from './unified/layers.ts';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'esm', platform: 'neutral', alias: { '@nct/nctgraphite': nct }, plugins: [{ name: 'paper-for-test', setup(build) { build.onResolve({ filter: /^paper$/ }, () => ({ path: 'paper', namespace: 'test-paper' })); build.onLoad({ filter: /.*/, namespace: 'test-paper' }, () => ({ contents: 'export default globalThis.__testPaper;', loader: 'js' })); } }], logLevel: 'silent' });
globalThis.__testPaper = paper;
const api = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString('base64')}`);
test('hover previews empty cells and lightens filled cells under the brush', () => {
  const canvas = api.defaultCanvas();
  let layer = api.createCellPaintLayer({ settings: { brushRadius: 35, brushShape: 'hex-pointy', brushAngle: 20, activationInset: 55 } });
  const point = { x: 480, y: 360 }, scope = new paper.PaperScope(); scope.setup(new scope.Size(canvas.width, canvas.height));
  const hits = api.cellBrushHits(layer, canvas, point);
  api.drawCellBrushPreview(scope, layer, canvas, point);
  const preview = scope.project.activeLayer.children.find(item => item.name === 'cell-brush-preview');
  assert.ok(hits.length > 0);
  assert.equal(preview.children.length, hits.length);
  layer = api.paintLayerAt(layer, canvas, point, 'paint');
  api.drawCellBrushPreview(scope, layer, canvas, point);
  const filledPreview = scope.project.activeLayer.children.find(item => item.name === 'cell-brush-preview');
  assert.equal(filledPreview.children.length, hits.length);
  assert.ok(filledPreview.children.every(child => child.fillColor.red === 1 && child.fillColor.green === 1 && child.fillColor.blue === 1 && child.fillColor.alpha > 0));
  layer = api.setLayerSetting(layer, 'showCellPreview', false, canvas);
  api.drawCellBrushPreview(scope, layer, canvas, point);
  assert.equal(scope.project.activeLayer.children.find(item => item.name === 'cell-brush-preview'), undefined);
  layer = api.setLayerSetting(layer, 'showCellPreview', true, canvas);
  api.drawCellBrushPreview(scope, layer, canvas, null);
  assert.equal(scope.project.activeLayer.children.find(item => item.name === 'cell-brush-preview'), undefined);
  scope.remove();
});
